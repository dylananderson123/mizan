// Builds the semi-procedural Journey chapters from fixed seeds and writes
// src/game/levels.data.js. Run with: npm run levels
//
// Every puzzle written here has passed: hydrate (schema), the exhaustive
// solver (unique where required), the logical solver (no guessing), and the
// difficulty evaluator (band as intended). tests/levels.test.js checks the
// written file again, so a hand edit cannot slip through.

import { writeFileSync } from 'node:fs';
import { createRng } from '../src/core/rng.js';
import { randomMagicSquare, randomLucasSquare } from '../src/core/generator.js';
import { carveFill, carveRestore } from '../src/core/carver.js';

const normal = (n) => (rng) => randomMagicSquare(n, rng);
const fresh = (rng) => randomLucasSquare(rng);

function fill(id, make, n, band, inscription, distractors = 0) {
  for (let k = 0; k < 400; k++) {
    const rng = createRng(`${id}#${k}`);
    const spec = carveFill(make(rng), n, rng, { band, id, meta: { inscription }, tries: 12, distractors });
    if (spec) return spec;
  }
  throw new Error(`Could not carve ${id} at band ${band}`);
}

function restore(id, make, n, swaps, locked, inscription) {
  for (let k = 0; k < 400; k++) {
    const rng = createRng(`${id}#${k}`);
    const spec = carveRestore(make(rng), n, rng, { swaps, locked, id, meta: { inscription }, tries: 20 });
    if (spec) return spec;
  }
  throw new Error(`Could not break ${id}`);
}

const t0 = Date.now();
const chapters = {
  // Chapter II leaves 1..9 behind. Any nine numbers of Lucas's form make a
  // square, and the target is always three times the centre. Learning the
  // Lo Shu by heart no longer solves anything.
  c2: [
    fill('c2-01', fresh, 3, 1, 'Other numbers'),
    fill('c2-02', fresh, 3, 2, 'Three times the centre'),
    fill('c2-03', fresh, 3, 2, 'Locked stones'),
    fill('c2-04', fresh, 3, 3, 'Only one fits'),
    fill('c2-05', fresh, 3, 2, 'A stone too many', 1),
    fill('c2-06', fresh, 3, 3, 'Two that do not belong', 2),
  ],
  c3: [
    restore('c3-01', normal(3), 3, 1, 0, 'Restore the square'),
    restore('c3-02', fresh, 3, 1, 3, 'Some stones hold'),
    restore('c3-03', normal(3), 3, 2, 0, 'Two wrongs'),
    restore('c3-04', fresh, 3, 2, 2, 'Patience'),
    restore('c3-05', fresh, 3, 3, 1, 'Three wrongs'),
  ],
  c4: [
    fill('c4-01', normal(4), 4, 1, 'Thirty four'),
    fill('c4-02', normal(4), 4, 2, 'Wider'),
    restore('c4-03', normal(4), 4, 1, 6, 'A broken sixteen'),
    fill('c4-04', normal(4), 4, 3, 'Sixteen stones'),
  ],
};

const body = `// GENERATED by tools/build-levels.mjs. Do not edit by hand.\n\nexport const GENERATED = ${JSON.stringify(chapters)};\n`;
writeFileSync(new URL('../src/game/levels.data.js', import.meta.url), body);
for (const [k, list] of Object.entries(chapters)) {
  console.log(k, list.map((p) => `${p.id}:${p.kind === 'fill' ? `b${p.meta.band} g${Object.keys(p.givens).length} t${p.target} pool${p.pool.length}` : `s${p.meta.swaps} t${p.target}`}`).join('  '));
}
console.log(`built in ${Date.now() - t0} ms`);
